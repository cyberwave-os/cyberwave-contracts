"""The Python SDK's controller types are written from their contract schemas.

``cyberwave/_contract_types.py`` in the SDK is generated by
``cyberwave_contracts._sdk_types``. The SDK lives beside this package only in the
monorepo, so the freshness check skips in the public contracts repository.
"""

from __future__ import annotations

import pytest

from cyberwave_contracts import _sdk_types

_TARGET = _sdk_types._MONOREPO_ROOT / _sdk_types.SDK_TYPES_RELATIVE


def test_the_sdk_types_are_current() -> None:
    if not _TARGET.is_file():
        pytest.skip("needs the monorepo checkout")
    assert _TARGET.read_text(encoding="utf-8") == _sdk_types.render(), (
        "the SDK's _contract_types.py is stale: run `make -C cyberwave-contracts models`"
    )


def test_the_sdk_keeps_the_names_it_has_always_exported() -> None:
    assert set(_sdk_types.SDK_TYPES.values()) == {
        "PolicyRefPayload",
        "ControlRuntimeTargetPayload",
    }


def test_a_schema_it_cannot_type_is_refused() -> None:
    schema = {
        "title": "x",
        "required": [],
        "properties": {"n": {"type": "number"}},
    }
    with pytest.raises(_sdk_types.UnsupportedSdkType):
        _sdk_types._render_class("X", schema)


def test_catalog_key_reaches_the_sdk_from_the_contract() -> None:
    assert '"catalog_key"' in _sdk_types.render()
