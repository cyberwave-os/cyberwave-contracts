"""The ``common.contract_id.v1`` vocabulary: every contract id a field may name.

Fields such as ``execution_contract``, ``output_contract`` and ``input_contract``
hold the id of a contract. They were free strings, so a typo, or an id nobody
registered, was indistinguishable from a real one. The schema's enum is the
manifest's payload contract ids plus :data:`UNREGISTERED_CONTRACT_IDS`, and it is
written by this module, never edited, so it cannot lag behind the manifest.

Regenerate it (``make -C cyberwave-contracts models`` does this first)::

    python3 -m cyberwave_contracts._contract_ids
"""

from __future__ import annotations

import json

from cyberwave_contracts.manifest import SCHEMAS_DIR, load_contracts

CONTRACT_ID = "common.contract_id.v1"

#: Ids production code already puts in ``input_contract``, ``output_contract`` or
#: ``execution_contract`` that no contract defines. Most are labels for what a
#: policy reads or writes, not payloads anything validates, so a schema for each
#: would be a guess until its owner says what it describes. Listing them keeps the
#: vocabulary accurate without inventing shapes. An id leaves this list when a
#: contract is registered for it (a test fails until it does).
#:
#: - ``control.*`` and ``locomotion.joint_target`` / ``locomotion.cmd_vel``:
#:   backend runtime targets and ``basic_simulation`` capabilities.
#: - ``manipulation.*`` and ``perception.locate_object``: the task contracts in
#:   ``lib/policy_contracts.py`` and the harness.
#: - ``actuator.channels.normalized`` and ``pose.mirror.kinematic``: written by
#:   ``cyberwave-sim`` into its run reports.
UNREGISTERED_CONTRACT_IDS: tuple[str, ...] = (
    "actuator.channels.normalized.v1",
    "control.free_body_velocity.v1",
    "control.joint_state.v1",
    "control.joint_target.v1",
    "locomotion.cmd_vel.v1",
    "locomotion.joint_target.v1",
    "manipulation.language_instruction.v1",
    "manipulation.pick_place.v1",
    "perception.locate_object.v1",
    "pose.mirror.kinematic.v1",
)


def registered_contract_ids() -> list[str]:
    """Payload contracts in the manifest: the ones a wire message can name."""
    return [c.id for c in load_contracts() if c.kind == "payload"]


def expected_schema() -> dict[str, object]:
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"https://schemas.cyberwave.com/{CONTRACT_ID}.schema.json",
        "title": "Cyberwave Contract Id",
        "description": (
            "The id of a contract, as a field such as `execution_contract`, "
            "`output_contract` or `input_contract` names it. Generated by "
            "python3 -m cyberwave_contracts._contract_ids; do not edit by hand. "
            "Most members are the manifest's payload contracts. These are ids "
            "production already uses that no contract defines yet, so they have "
            "no schema: " + ", ".join(UNREGISTERED_CONTRACT_IDS) + "."
        ),
        "type": "string",
        "enum": sorted({*registered_contract_ids(), *UNREGISTERED_CONTRACT_IDS}),
    }


def render() -> str:
    return json.dumps(expected_schema(), indent=2) + "\n"


def main() -> None:
    (SCHEMAS_DIR / f"{CONTRACT_ID}.schema.json").write_text(render(), encoding="utf-8")


if __name__ == "__main__":
    main()
